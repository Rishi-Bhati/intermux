def set_window_icon(root: Any) -> None:
    """Use the InterMux icon for root and the windows it opens; ignored where Tk cannot show it."""
    try:
        import tkinter as tk

        image = tk.PhotoImage(master=root, data=ICON_PNG_BASE64)
        root.iconphoto(True, image)
        root._intermux_icon = image  # keep a reference; Tk drops unreferenced images
    except Exception:  # noqa: BLE001 - an icon is never worth failing the window over
        pass
